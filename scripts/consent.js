// Согласие на файлы cookie и загрузка счётчика.
//
// Что делает: показывает баннер, если решения ещё нет, запоминает выбор
// и подгружает счётчик — только после «Принять» (An2).
//
// Чего НЕ делает: не вставляет счётчик в разметку заранее и не грузит его
// «на всякий случай». До согласия счётчика на странице нет вовсе.
//
// Осознанное следствие: визит считается с момента загрузки счётчика.
// Первые секунды и переходы до нажатия в статистику не попадут —
// это плата за законность, а не дефект измерения (An2).
//
// Факт согласия хранится вместе с версией текста и датой: при споре
// важно не только «согласился», но и «с чем именно согласился» (L7).
//
// Здесь же закреплённая панель действий и окно обратного звонка — ниже,
// раздел «Панель». Отдельным файлом панель была до задачи 64: седьмой
// скрипт на странице вместе с виджетом Turnstile выходил за бюджет T6,
// а показ панели всё равно ждёт ответа на баннер.

const КЛЮЧ = 'alfa-consent';

const баннер = document.querySelector('[data-consent]');
const панель = document.querySelector('[data-sticky-panel]');
const окно = document.querySelector('[data-modal]');

// Место под закреплённым снизу (Cv14) — переменная у <html>, а занимает
// его нижнее поле подвала (Footer.astro, задача 70). Отступ у body ложился
// под подвал белой полосой: фон body светлее подвала. Пусто — места нет
const местоСнизу = (высота) => {
  if (высота) document.documentElement.style.setProperty('--fixed-bottom-h', `${высота}px`);
  else document.documentElement.style.removeProperty('--fixed-bottom-h');
};

// ── Панель ──
//
// Показывается только после того, как человек ответил на баннер согласия
// (Pt22): два закреплённых элемента на нижней кромке вдвоём занимают
// половину узкого экрана (Cv13). Ответ приходит событием из раздела
// «Согласие» ниже — и при первом визите, и при сохранённом решении.
//
// Открытие окна — нативным методом showModal: он сам удерживает фокус
// внутри и закрывает по клавише выхода (Cv25). Ничего из этого
// здесь не написано вручную, потому что написанное вручную обычно теряет
// либо удержание фокуса, либо возврат фокуса на кнопку после закрытия.

if (панель) {
  // Первый экран (задача 68, ставка (б) задачи 63): пока его кнопки
  // в окне, панель их только повторяет и закрывает низ экрана. Она
  // уезжает за нижний край (data-away) и выезжает, когда кнопки ушли
  // вверх. Кнопок нет — смотрим на всю полосу первого экрана (PageHero,
  // главная). Метки нет вовсе — панель как раньше, сразу после ответа
  const первыйЭкран = document.querySelector('[data-first-screen]');

  // Cv14: панель не должна перекрывать последний блок страницы.
  // Отступ ставится вместе с показом, а не в стилях: пока панели нет,
  // пустое место внизу выглядело бы обрывом вёрстки. Уехавшая панель
  // место под ней сохраняет: снимать и ставить его на каждом проезде —
  // менять высоту документа под пальцем.
  // Mp10: и фокус под неё не уходит — тот же отступ у области прокрутки,
  // по нему браузер докручивает элемент при переходе клавишей Tab.
  // Этот — только пока панель видна: уехавшая ничего не закрывает.
  // Пока баннер открыт снова из подвала, он выше и отступы его — не трогаем
  // На широком экране панели нет — её действия в закреплённой шапке
  // (StickyPanel.astro, задача 61): высота нулевая, и отступы снимаются,
  // в том числе оставшиеся с узкого окна до его расширения. Узнаём
  // по высоте самой панели, а не по числу: точка перелома записана
  // в стилях, второго места для неё здесь не заводим
  const компенсировать = () => {
    if (баннер && !баннер.hidden) return;
    const высота = панель.offsetHeight;
    const видна = высота && !панель.hasAttribute('data-away');
    местоСнизу(высота);
    document.documentElement.style.scrollPaddingBlockEnd = видна ? `calc(${высота}px + var(--gap-xs))` : '';
  };

  // Панель выехала, когда фокус уже стоит у нижнего края: браузер
  // докрутил его без отступа, и выехавшая закрыла бы его. Докручиваем
  // заново — уже с отступом. Только фокус с клавиатуры: под пальцем
  // и мышью страница не прыгает
  const освободитьФокус = () => {
    const el = document.activeElement;
    if (!el || el === document.body || панель.contains(el) || !el.matches(':focus-visible')) return;
    if (el.getBoundingClientRect().bottom > innerHeight - панель.offsetHeight) {
      el.scrollIntoView({ block: 'nearest' });
    }
  };

  const уехать = (да) => {
    if (панель.hasAttribute('data-away') === да) return;
    панель.toggleAttribute('data-away', да);
    if (панель.hidden) return;
    компенсировать();
    if (!да) освободитьФокус();
  };

  if (первыйЭкран) {
    панель.setAttribute('data-away', '');
    // Кнопки в окне или ещё ниже его — панель внизу не нужна. Выше окна —
    // ушли, панель выезжает. Порог 0: любой видимый край кнопок считается.
    // Записей за вызов бывает несколько, по порядку снятия, — верна последняя
    // (задача 113): при перезагрузке на занятой странице первая снята до
    // восстановления прокрутки («кнопки в окне»), вторая — после, и по первой
    // панель уезжала внизу страницы и там оставалась
    new IntersectionObserver((записи) => {
      const з = записи[записи.length - 1];
      уехать(з.isIntersecting || з.boundingClientRect.top >= innerHeight);
    }).observe(первыйЭкран);
  }

  const показать = () => {
    панель.hidden = false;
    компенсировать();
  };

  // Баннер открыли снова из подвала — панель уходит вместе со своим
  // отступом, баннер следом ставит свой. После ответа вернётся по закрытию
  const спрятать = () => {
    панель.hidden = true;
    местоСнизу(0);
    document.documentElement.style.scrollPaddingBlockEnd = '';
  };

  // Без once: баннер можно открыть из подвала и закрыть снова —
  // скрываясь, он снимает свой отступ, и панель возвращает свой
  document.addEventListener('consent:closed', показать);
  document.addEventListener('consent:opened', спрятать);

  // Подписка выше стоит раньше логики согласия в этом же файле — событие
  // о сохранённом решении она застаёт. Баннера на странице нет — ждать
  // нечего, панель показывается сразу. До задачи 64 панель жила отдельным
  // файлом и держалась на порядке двух defer-скриптов в разметке
  if (!баннер) показать();

  window.addEventListener('resize', () => {
    if (!панель.hidden) компенсировать();
  });
}

if (окно) {
  // Открывающих две: в панели (узкий экран) и в шапке (широкий, задача 61).
  // Окно и форма в нём одни — тип формы и цель у обеих общие
  const открыть = document.querySelectorAll('[data-modal-open]');
  const закрыть = окно.querySelector('[data-modal-close]');

  открыть.forEach((кнопка) => кнопка.addEventListener('click', () => окно.showModal()));
  закрыть?.addEventListener('click', () => окно.close());

  // Клик по затемнению за пределами окна. Событие приходит на сам диалог,
  // потому что затемнение — его псевдоэлемент: отличаем по координатам
  окно.addEventListener('click', (e) => {
    if (e.target !== окно) return;
    const р = окно.getBoundingClientRect();
    const внутри = e.clientX >= р.left && e.clientX <= р.right
      && e.clientY >= р.top && e.clientY <= р.bottom;
    if (!внутри) окно.close();
  });
}

// ── Согласие ──

if (баннер) {
  const версия = баннер.dataset.consentVersion || '';

  // Номер счётчика — из site.ts через разметку баннера. Не цифры (пометка
  // «заполнить», пусто) — счётчика нет: номер выдаёт собственник,
  // до этого скрипт корректно ничего не грузит и молчит, а не падает.
  // Квадратных скобок пометки здесь нет намеренно: проверка сборки
  // читает и скрипты и сочла бы комментарий незаполненным местом
  const номер = баннер.dataset.metrika || '';
  const СЧЁТЧИК = /^\d+$/.test(номер) ? Number(номер) : 0;

  const прочитать = () => {
    try {
      const сырое = localStorage.getItem(КЛЮЧ);
      return сырое ? JSON.parse(сырое) : null;
    } catch {
      // Приватный режим и запрет хранилища: решение не сохраняется,
      // баннер покажется снова. Это лучше, чем падение скрипта
      return null;
    }
  };

  const записать = (решение) => {
    try {
      localStorage.setItem(КЛЮЧ, JSON.stringify({
        решение,
        версия,
        дата: new Date().toISOString(),
      }));
    } catch { /* хранилище недоступно — решение действует до перезагрузки */ }
  };

  // Счётчик подключается внешним файлом, без встроенного кода:
  // встроенный конфликтует с политикой безопасности, а домен аналитики
  // в ней уже разрешён в трёх директивах (An5)
  const включитьСчётчик = () => {
    if (!СЧЁТЧИК || document.getElementById('metrika')) return;
    const s = document.createElement('script');
    s.id = 'metrika';
    s.async = true;
    s.src = 'https://mc.yandex.ru/metrika/tag.js';
    // Очередь вызовов до загрузки — тем же приёмом, что код счётчика с сайта
    // Метрики: функция копит arguments, загруженный счётчик их забирает.
    // Сверять с кодом счётчика при подключении (W2)
    window.ym = window.ym || function () { (window.ym.a = window.ym.a || []).push(arguments); };
    window.ym.l = Date.now();
    // Вебвизор и карта кликов выключены до запуска (решение Марата
    // 11.10, задача 74). Три причины:
    //  - плеер вебвизора и карта кликов показывают страницу в рамке
    //    на стороне Метрики, а .htaccess это запрещает
    //    (frame-ancestors 'none', X-Frame-Options: DENY);
    //  - поля форм не размечены классами скрытия ввода Метрики —
    //    вебвизор писал бы имя и телефон до отправки заявки;
    //  - постоянная запись сессий — нагрузка на поток страницы (An10).
    // Возвращать, когда появится трафик и есть что смотреть, и только
    // вместе: домены Метрики в frame-ancestors по её справке, классы
    // скрытия ввода на полях всех форм, запись не на 100% визитов (An10)
    window.ym(СЧЁТЧИК, 'init', {
      webvisor: false,
      clickmap: false,
      trackLinks: true,
      accurateTrackBounce: true,
    });
    s.addEventListener('load', () => {
      // goals.js ждёт метки и события: до загрузки его вызовы не уходят,
      // а без согласия загрузки не будет никогда (An2)
      s.dataset.loaded = '';
      document.dispatchEvent(new CustomEvent('metrika:ready'));
    });
    document.head.appendChild(s);
  };

  // Отказ в другой вкладке (L6): там страницу перезагрузили, а здесь счётчик
  // живёт и сам шлёт переходы. Событие storage приходит только в другие
  // вкладки; key === null — хранилище очищено целиком, решения больше нет.
  // Цена та же, что у отказа здесь: несохранённый ввод в формах
  window.addEventListener('storage', (e) => {
    if ((e.key !== null && e.key !== КЛЮЧ) || !document.getElementById('metrika')) return;
    if (прочитать()?.решение !== 'accept') location.reload();
  });

  // Панель действий ждёт этого события: два закреплённых элемента
  // одновременно на узком экране занимают половину экрана (Cv13, Pt22)
  const сообщитьЧтоЗакрыт = () => {
    document.dispatchEvent(new CustomEvent('consent:closed'));
  };

  // Mp10: фокус не уходит под баннер. Браузер, переводя фокус клавишей Tab,
  // докручивает элемент до видимой области за вычетом scroll-padding —
  // поэтому нижний отступ области равен высоте баннера, пока он показан.
  // Место снизу — чтобы последним ссылкам подвала было куда подняться:
  // без него документ кончается раньше, чем они выходят из-под баннера.
  // Значения в стиле элементов, а не в CSS: высота баннера зависит от ширины
  // и известна только после отрисовки. Панель ставит свои, когда баннер скрыт
  const корень = document.documentElement;
  const отступы = () => {
    if (баннер.hidden) return;
    const высота = баннер.offsetHeight;
    местоСнизу(высота);
    корень.style.scrollPaddingBlockEnd = `calc(${высота}px + var(--gap-xs))`;
  };

  // Панель на это прячется: баннер, открытый снова из подвала, стоит
  // поверх неё, и вдвоём они закрывают нижнюю часть экрана (Cv13, Pt22).
  // Событие — до отступов: панель снимает свои, баннер ставит свои
  const показать = () => {
    баннер.hidden = false;
    document.dispatchEvent(new CustomEvent('consent:opened'));
    отступы();
  };

  const скрыть = () => {
    баннер.hidden = true;
    местоСнизу(0);
    корень.style.scrollPaddingBlockEnd = '';
    сообщитьЧтоЗакрыт();
  };

  window.addEventListener('resize', отступы);

  // Кнопка подвала, из которой баннер открыли снова. Пусто — первый визит
  let открытИз = null;

  // Фокус не остаётся на скрытой кнопке: следующий Tab начался бы
  // от невидимого элемента (2.4.3). Открыли из подвала — фокус туда же,
  // откуда пришли. Первый визит — на <main>: баннер стоит первым в обходе,
  // и дальше человек идёт в содержимое. Без preventScroll страница
  // прыгнула бы к началу <main>
  const вернутьФокус = () => {
    if (открытИз) {
      открытИз.focus();
      return;
    }
    const главное = document.querySelector('main');
    if (!главное) return;
    главное.setAttribute('tabindex', '-1');
    главное.focus({ preventScroll: true });
  };

  const решить = (решение) => {
    // Смотрим до скрытия: после него браузер сам сбросит фокус на body.
    // Фокус не в баннере (Safari не ставит его на кнопку по щелчку) —
    // не трогаем
    const фокусВБаннере = баннер.contains(document.activeElement);
    записать(решение);
    // Отказ после согласия (L6): счётчик уже на странице, и выгрузить его
    // нечем — вебвизор и карта кликов шлют данные сами, без вызовов
    // из goals.js. Перезагрузка даёт страницу без него: решение записано,
    // и при загрузке счётчик не включится. Цена — несохранённый ввод в формах
    if (решение !== 'accept' && document.getElementById('metrika')) {
      location.reload();
      return;
    }
    if (решение === 'accept') включитьСчётчик();
    скрыть();
    if (фокусВБаннере) вернутьФокус();
    открытИз = null;
  };

  баннер.querySelector('[data-consent-accept]')
    ?.addEventListener('click', () => решить('accept'));

  баннер.querySelector('[data-consent-decline]')
    ?.addEventListener('click', () => решить('decline'));

  // «Настроить» раскрывает состав категорий, а не уводит на другую страницу:
  // выбор должен оставаться в одном месте
  баннер.querySelector('[data-consent-settings]')
    ?.addEventListener('click', (e) => {
      const блок = баннер.querySelector('[data-consent-detail]');
      if (!блок) return;
      блок.hidden = !блок.hidden;
      e.currentTarget.setAttribute('aria-expanded', String(!блок.hidden));
      // Баннер вырос или сжался — отступы по новой высоте (Mp10)
      отступы();
    });

  // Отзыв согласия из подвала: тот же баннер, тот же выбор.
  // Требование L6 — дать возможность передумать
  document.querySelectorAll('[data-consent-reopen]').forEach((кнопка) => {
    кнопка.addEventListener('click', () => {
      открытИз = кнопка;
      показать();
      баннер.querySelector('[data-consent-accept]')?.focus();
    });
  });

  const сохранённое = прочитать();

  if (!сохранённое || сохранённое.версия !== версия) {
    // Решения нет или текст согласия с тех пор изменился — спрашиваем заново
    показать();
  } else {
    if (сохранённое.решение === 'accept') включитьСчётчик();
    сообщитьЧтоЗакрыт();
  }
}
